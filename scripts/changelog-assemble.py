#!/usr/bin/env python3
"""Assemble per-surface synthesis fragments into one changelog file.

Usage:
    python3 scripts/changelog-assemble.py <version> <base_tag> <head_tag> \
        [--work-dir .work/changelog] [--output-dir lexicon/changelog/platform]

Reads <work-dir>/<version>/fragment.<surface>.md. Lines starting with
`SUMMARY:` become rows of the Summary table (in fragment order); everything
else is the surface body. Writes <output-dir>/<version>.md.

Synthesis agents write fragments in parallel instead of appending to the
shared output file, so no agent can clobber another's section.
"""

import argparse
import datetime
import glob
import os
import re
import sys

# Known surfaces first, in this order; unknown ones follow alphabetically.
ORDER = [
    "rust",
    "rust-core",
    "rust-sdk",
    "rust-dpp",
    "rust-drive",
    "rust-ffi",
    "grpc",
    "js",
    "swift",
    "all",
]
FRAGMENT_RE = re.compile(r"fragment\.([a-z0-9-]+)\.md$")


def sort_key(path):
    surface = FRAGMENT_RE.search(path).group(1)
    return (ORDER.index(surface) if surface in ORDER else len(ORDER), surface)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("version")
    parser.add_argument("base_tag")
    parser.add_argument("head_tag")
    parser.add_argument("--work-dir", default=".work/changelog")
    parser.add_argument("--output-dir", default="lexicon/changelog/platform")
    args = parser.parse_args()

    pattern = os.path.join(args.work_dir, args.version, "fragment.*.md")
    frags = sorted(
        (p for p in glob.glob(pattern) if FRAGMENT_RE.search(p)), key=sort_key
    )
    if not frags:
        sys.exit(f"no fragments match {pattern}")

    summary, body = [], []
    for path in frags:
        with open(path) as f:
            for line in f.read().splitlines():
                if line.startswith("SUMMARY:"):
                    summary.append(line[len("SUMMARY:") :].strip())
                else:
                    body.append(line)
        body.append("")
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(body)).strip() + "\n"

    header = f"""# Platform API Changelog — {args.version}
<!-- Auto-generated by update-api-changelog. Do not edit. Generated: {datetime.date.today()} -->
<!-- Diff: {args.base_tag}..{args.head_tag} | platform | surfaces: rust, grpc, js, swift -->

> **{args.head_tag}** vs **{args.base_tag}**. `±` = changed signature, `+` added, `−` removed, `⚠` deprecated.
> Search by symbol/RPC name in the Keyword column.

## Summary
| Surface | + | − | ± | ⚠ | Breaking |
|---------|---|---|---|---|----------|
"""
    os.makedirs(args.output_dir, exist_ok=True)
    out_path = os.path.join(args.output_dir, f"{args.version}.md")
    with open(out_path, "w") as f:
        f.write(header + "\n".join(summary) + "\n\n" + text)
    print(f"wrote {out_path}: {len(frags)} fragments, {len(summary)} summary rows")


if __name__ == "__main__":
    main()
